/*
 * Cordova hook: add `use_modular_headers!` to platforms/ios/Podfile.
 *
 * cordova-ios auto-generates the Podfile and does not expose a config.xml/plugin.xml
 * knob for arbitrary CocoaPods directives other than `use_frameworks!` and
 * `inhibit_all_warnings!` (see cordova-ios/lib/Podfile.js declarationRegexpMap).
 * Cordova links pods statically by default (no `use_frameworks!`), and recent
 * Firebase pods (pulled in via `pod 'FirebaseMessaging'`) depend on GoogleUtilities,
 * which does not define modules -- `pod install` refuses to proceed under static
 * linking unless `use_modular_headers!` is set.
 *
 * The generated Podfile is fully rewritten on every `prepare`, but cordova-ios seeds
 * its in-memory declarations by parsing whatever already sits between the
 * `platform :ios, 'x.y'` and `target 'App' do` lines (any non-comment line there is
 * treated as a raw declaration and re-emitted verbatim). So patching the file before
 * cordova-ios's own prepare runs (before_prepare, ahead of `preparePlatforms`) is
 * enough for our line to survive the regeneration.
 */

const fs = require('fs');
const path = require('path');

const DECLARATION = 'use_modular_headers!';

function exists(filePath) {
  try {
    fs.accessSync(filePath, fs.constants.F_OK);
    return true;
  } catch (_) {
    return false;
  }
}

function alreadyPresent(text) {
  return new RegExp(`^\\s*${DECLARATION}\\s*$`, 'm').test(text);
}

function insertIntoExisting(text) {
  const platformLineRe = /(platform :ios,\s*'[^']+'\s*\n)/;
  if (!platformLineRe.test(text)) return null;

  return text.replace(platformLineRe, `$1${DECLARATION}\n`);
}

function seedTemplate() {
  return (
    '# DO NOT MODIFY -- auto-generated by Apache Cordova\n' +
    "platform :ios, '15.0'\n" +
    `${DECLARATION}\n` +
    "target 'App' do\n" +
    "\tproject 'App.xcodeproj'\n" +
    'end\n'
  );
}

module.exports = function (context) {
  const opts = (context && context.opts) || {};
  // HooksRunner.fire() normalizes `opts.cordova.platforms` for every hook type
  // (see cordova-lib/src/hooks/HooksRunner.js). `opts.platforms` is only ever set
  // by the `prepare` command itself (before_prepare/after_prepare) -- for
  // before_plugin_install/after_plugin_install (fired during `cordova plugin add`,
  // including plugin restoration onto a freshly added platform) the platform list
  // only exists at `opts.cordova.platforms`. Check both so this hook actually runs
  // on every path that can trigger `pod install`.
  const platformsList = (opts.cordova && opts.cordova.platforms) || opts.platforms || [];
  if (!platformsList.includes('ios')) return;

  const projectRoot =
    opts.projectRoot ||
    (opts.cordova && opts.cordova.project && opts.cordova.project.root) ||
    null;

  if (!projectRoot) return;

  const iosPlatformDir = path.join(projectRoot, 'platforms', 'ios');
  if (!exists(iosPlatformDir)) return;

  const podfilePath = path.join(iosPlatformDir, 'Podfile');

  let result;
  let action;

  if (exists(podfilePath)) {
    const original = fs.readFileSync(podfilePath, 'utf8');
    if (alreadyPresent(original)) {
      action = 'already-present';
      result = original;
    } else {
      const patched = insertIntoExisting(original);
      if (!patched) {
        // eslint-disable-next-line no-console
        console.log('cordova-plugin-reteno: iOS setup: Podfile format not recognized, skipping use_modular_headers! patch.');
        return;
      }
      action = 'patched';
      result = patched;
    }
  } else {
    action = 'seeded';
    result = seedTemplate();
  }

  if (action !== 'already-present') {
    fs.writeFileSync(podfilePath, result, 'utf8');
  }

  // eslint-disable-next-line no-console
  console.log(`cordova-plugin-reteno: iOS setup: Podfile use_modular_headers!=${action}.`);
};
